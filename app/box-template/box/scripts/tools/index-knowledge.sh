#!/usr/bin/env bash
set -euo pipefail
# index-knowledge.sh — (re)build knowladge/INDEX.md from the source tree.
# The index is what the agent reads first to know which material exists and
# where. Run it after adding/removing sources:
#   box/scripts/tools/index-knowledge.sh

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BOX_DIR="$(cd "$SELF_DIR/../../.." && pwd)"
KN="$BOX_DIR/knowladge"
OUT="$KN/INDEX.md"

[ -d "$KN" ] || { echo "no knowladge/ dir at $KN" >&2; exit 1; }

{
  echo "# Knowledge index"
  echo
  echo "Auto-generated by \`box/scripts/tools/index-knowledge.sh\` on $(date '+%F %T')."
  echo "This is the map of the learning sources stored under \`knowladge/\`."
  echo "Read it first; then open the specific files you need, and record what you"
  echo "learn in \`memory/\` (see CLAUDE.md)."
  echo
  echo "## Collections"
  echo
  for d in "$KN"/*/; do
    [ -d "$d" ] || continue
    name="$(basename "$d")"
    [ "$name" = "memory" ] && continue
    n="$(find "$d" -type f | wc -l | tr -d ' ')"
    echo "### $name  ($n files)"
    echo
    # one level of subfolders
    for sub in "$d"*/; do
      [ -d "$sub" ] || continue
      sn="$(basename "$sub")"
      sc="$(find "$sub" -type f | wc -l | tr -d ' ')"
      echo "- **$sn/** — $sc file(s)"
    done
    echo
    echo "<details><summary>Files</summary>"
    echo
    find "$d" -type f -printf '%P\n' | sort | sed 's/^/- /'
    echo
    echo "</details>"
    echo
  done
} > "$OUT"

echo "wrote $OUT ($(find "$KN" -type f ! -name INDEX.md | wc -l | tr -d ' ') source files indexed)"
